    private java.util.List<Subject> inputSubjectsDialog(int n, java.util.List<Subject> currentSubjects) {
        java.util.List<Subject> list = new java.util.ArrayList<>();
        for (int i = 0; i < n; i++) {
            Subject oldSub = (currentSubjects != null && i < currentSubjects.size()) ? currentSubjects.get(i) : null;

            JTextField fName = new JTextField(oldSub != null ? oldSub.getName() : "Môn " + (i + 1));
            JTextField fCC = new JTextField(oldSub != null ? String.valueOf(oldSub.getCc()) : "0");
            JTextField fGK = new JTextField(oldSub != null ? String.valueOf(oldSub.getGk()) : "0");
            JTextField fCK = new JTextField(oldSub != null ? String.valueOf(oldSub.getCk()) : "0");

            Object[] message = {
                "Tên môn:", fName,
                "Điểm Chuyên cần (20%):", fCC,
                "Điểm Giữa kỳ (30%):", fGK,
                "Điểm Cuối kỳ (50%):", fCK
            };

            int option = javax.swing.JOptionPane.showConfirmDialog(this, message, "Nhập môn " + (i + 1) + "/" + n, javax.swing.JOptionPane.OK_CANCEL_OPTION);
            if (option == javax.swing.JOptionPane.OK_OPTION) {
                try {
                    double cc = Double.parseDouble(fCC.getText());
                    double gk = Double.parseDouble(fGK.getText());
                    double ck = Double.parseDouble(fCK.getText());

                    if (cc < 0 || cc > 10 || gk < 0 || gk > 10 || ck < 0 || ck > 10) {
                        javax.swing.JOptionPane.showMessageDialog(this, "Điểm phải từ 0-10!");
                        i--;
                        continue;
                    }
                    list.add(new Subject(fName.getText().trim(), cc, gk, ck));
                } catch (Exception e) {
                    javax.swing.JOptionPane.showMessageDialog(this, "Điểm phải là số!");
                    i--;
                }
            } else {
                return null;
            }
        }
        return list;
    }

    private void renderTable() {
        tableModel.setRowCount(0); // Xóa dữ liệu cũ trên bảng
        int stt = 1;

        for (Student st : studentList) {
            List<Subject> subjects = st.getSubjects();

            if (subjects.isEmpty()) {
                // Sinh viên chưa có môn nào
                tableModel.addRow(new Object[]{
                    stt++,
                    st.getId(),
                    st.getName(),
                    0,
                    "-", "-", "-", "-",
                    st.getGpa()
                });
            } else {
                // Duyệt từng môn học của sinh viên
                for (int i = 0; i < subjects.size(); i++) {
                    Subject sub = subjects.get(i);

                    if (i == 0) {
                        // Dòng môn đầu tiên: Hiển thị đầy đủ thông tin sinh viên
                        tableModel.addRow(new Object[]{
                            stt++,
                            st.getId(),
                            st.getName(),
                            subjects.size(),
                            sub.getName(),
                            sub.getCc(),
                            sub.getGk(),
                            sub.getCk(),
                            st.getGpa()
                        });
                    } else {
                        // Các dòng môn tiếp theo: Để trống thông tin chung
                        tableModel.addRow(new Object[]{
                            "", "", "", "",
                            sub.getName(),
                            sub.getCc(),
                            sub.getGk(),
                            sub.getCk(),
                            ""
                        });
                    }
                }
            }
        }
    }

    private void clearForm() {
        txtId.setText("");
        txtName.setText("");
        txtNumSubjects.setText("");
        tblStudents.clearSelection();
    }
