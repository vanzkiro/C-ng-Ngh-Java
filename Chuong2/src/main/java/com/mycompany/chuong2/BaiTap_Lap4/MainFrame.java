    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        // TODO add your handling code here:
        String id = txtId.getText().trim();
        String name = txtName.getText().trim();
        String numStr = txtNumSubjects.getText().trim();

        if (id.isEmpty() || name.isEmpty() || numStr.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Vui lòng nhập đầy đủ thông tin!");
            return;
        }

        try {
            int n = Integer.parseInt(numStr);
            if (n <= 0) {
                javax.swing.JOptionPane.showMessageDialog(this, "Số môn N phải > 0!");
                return;
            }

            java.util.List<Subject> subjects = inputSubjectsDialog(n, null);
            if (subjects != null) {
                Student st = new Student(id, name);
                st.setSubjects(subjects);
                studentList.add(st);
                renderTable();
                clearForm();
            }
        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Số môn phải là số nguyên!");
        }
    }//GEN-LAST:event_btnAddActionPerformed

    private void btnEditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditActionPerformed
        // TODO add your handling code here:
        int row = tblStudents.getSelectedRow();
        if (row < 0) {
            javax.swing.JOptionPane.showMessageDialog(this, "Vui lòng chọn sinh viên cần sửa!");
            return;
        }

        try {
            int n = Integer.parseInt(txtNumSubjects.getText().trim());
            Student st = studentList.get(row);

            java.util.List<Subject> subjects = inputSubjectsDialog(n, st.getSubjects());
            if (subjects != null) {
                st.setId(txtId.getText().trim());
                st.setName(txtName.getText().trim());
                st.setSubjects(subjects);
                renderTable();
                clearForm();
            }
        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Số môn phải là số nguyên!");
        }
    }//GEN-LAST:event_btnEditActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        // TODO add your handling code here:
        int row = tblStudents.getSelectedRow();
        if (row < 0) {
            javax.swing.JOptionPane.showMessageDialog(this, "Vui lòng chọn sinh viên cần xóa!");
            return;
        }

        // Tìm Mã SV của dòng đang chọn
        String studentId = tableModel.getValueAt(row, 1).toString();
        while (studentId.isEmpty() && row > 0) {
            row--;
            studentId = tableModel.getValueAt(row, 1).toString();
        }

        int confirm = javax.swing.JOptionPane.showConfirmDialog(
            this, "Bạn có chắc chắn muốn xóa sinh viên này?", "Xác nhận xóa", javax.swing.JOptionPane.YES_NO_OPTION
        );

        if (confirm == javax.swing.JOptionPane.YES_OPTION) {
            // Tìm và xóa trong danh sách dữ liệu
            final String targetId = studentId;
            studentList.removeIf(st -> st.getId().equals(targetId));

            renderTable(); // Vẽ lại bảng
            clearForm();   // Xóa trắng form
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

