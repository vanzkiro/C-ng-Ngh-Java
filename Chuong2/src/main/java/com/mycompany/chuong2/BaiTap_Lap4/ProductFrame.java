    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        // TODO add your handling code here:
        DefaultTableModel tableModel = (DefaultTableModel) tblSanPham.getModel();
        String ma = txtMaSP.getText().trim();
        String ten = txtTenSP.getText().trim();
        String slStr = txtSoLuong.getText().trim();

        if (!isValidMaSP(ma)) {
            JOptionPane.showMessageDialog(this, "Mã SP phải gồm đúng 5 ký tự chữ và số (VD: SP001)!");
            return;
        }

        // Kiểm tra trùng mã SP (Đã sửa lỗi NullPointerException)
        for (int i = 0; i < tableModel.getRowCount(); i++) {
            Object val = tableModel.getValueAt(i, 0);
            if (val != null && val.toString().equalsIgnoreCase(ma)) {
                JOptionPane.showMessageDialog(this, "Mã SP này đã tồn tại! Vui lòng nhập mã khác.");
                return;
            }
        }

        if (ten.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Tên sản phẩm không được để trống!");
            return;
        }

        try {
            int sl = Integer.parseInt(slStr);
            if (sl < 0) {
                JOptionPane.showMessageDialog(this, "Số lượng phải >= 0!");
                return;
            }

            double gia = (sl < 10) ? 10000 : 5000;
            double tienHang = sl * gia;

            // Hiển thị đơn giá tự động lên ô 
            txtDonGia.setText(String.format("%.0f", gia));

            tableModel.addRow(new Object[]{ma, ten, sl, gia, tienHang});
            clearForm();
            JOptionPane.showMessageDialog(this, "Thêm sản phẩm thành công!");

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Số lượng phải là số nguyên!");
        }
    }//GEN-LAST:event_btnAddActionPerformed

    private void btnEditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditActionPerformed
        // TODO add your handling code here:
        DefaultTableModel tableModel = (DefaultTableModel) tblSanPham.getModel();
            int selectedRow = tblSanPham.getSelectedRow();

            if (selectedRow < 0) {
                JOptionPane.showMessageDialog(this, "Vui lòng chọn dòng cần sửa trong bảng!");
                return;
            }

            String ten = txtTenSP.getText().trim();
            String slStr = txtSoLuong.getText().trim();

            if (ten.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Tên sản phẩm không được để trống!");
                return;
            }

            try {
                int sl = Integer.parseInt(slStr);
                if (sl < 0) {
                    JOptionPane.showMessageDialog(this, "Số lượng phải >= 0!");
                    return;
                }

                // Tính lại Đơn giá & Tiền hàng
                double gia = (sl < 10) ? 10000 : 5000;
                double tienHang = sl * gia;

                txtDonGia.setText(String.format("%.0f", gia));

                // Cập nhật giá trị vào dòng đã chọn trong Bảng
                tableModel.setValueAt(ten, selectedRow, 1);
                tableModel.setValueAt(sl, selectedRow, 2);
                tableModel.setValueAt(gia, selectedRow, 3);
                tableModel.setValueAt(tienHang, selectedRow, 4);

                clearForm();
                JOptionPane.showMessageDialog(this, "Cập nhật thành công!");

            } catch (NumberFormatException e) {
                JOptionPane.showMessageDialog(this, "Số lượng phải là số nguyên!");
            }
        
    }//GEN-LAST:event_btnEditActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        // TODO add your handling code here:
        DefaultTableModel tableModel = (DefaultTableModel) tblSanPham.getModel();
        int selectedRow = tblSanPham.getSelectedRow();

        if (selectedRow < 0) {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn dòng cần xóa!");
            return;
        }

        int confirm = JOptionPane.showConfirmDialog(this, "Bạn có chắc chắn muốn xóa?", "Xác nhận", JOptionPane.YES_NO_OPTION);
        if (confirm == JOptionPane.YES_OPTION) {
            tableModel.removeRow(selectedRow);
            clearForm();
            JOptionPane.showMessageDialog(this, "Xóa sản phẩm thành công!");
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

    private void tblSanPhamMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblSanPhamMouseClicked
        // TODO add your handling code here:
        DefaultTableModel tableModel = (DefaultTableModel) tblSanPham.getModel();
        int selectedRow = tblSanPham.getSelectedRow();

        if (selectedRow >= 0) {
            Object ma = tableModel.getValueAt(selectedRow, 0);
            Object ten = tableModel.getValueAt(selectedRow, 1);
            Object sl = tableModel.getValueAt(selectedRow, 2);
            Object gia = tableModel.getValueAt(selectedRow, 3);

            txtMaSP.setText(ma != null ? ma.toString() : "");
            txtTenSP.setText(ten != null ? ten.toString() : "");
            txtSoLuong.setText(sl != null ? sl.toString() : "");
            txtDonGia.setText(gia != null ? gia.toString() : "");

            txtMaSP.setEditable(false);
        }
    }//GEN-LAST:event_tblSanPhamMouseClicked

