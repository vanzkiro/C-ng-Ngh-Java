    private boolean isValidMaSP(String ma) {
        if (ma == null || ma.length() != 5) {
            return false;
        }
        boolean hasLetter = ma.matches(".*[a-zA-Z].*");
        boolean hasDigit = ma.matches(".*[0-9].*");
        boolean isAlphanumeric = ma.matches("[a-zA-Z0-9]{5}");
        return isAlphanumeric && hasLetter && hasDigit;
    }

